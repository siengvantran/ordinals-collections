// Copies the shared core rules and the dictionary into the Edge Function, so
// the server runs exactly the code the browser and the tests run.
//   npm run sync          copy
//   npm run sync -- --check   exit 1 if the copy is stale (used by npm test)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'js/core');
const dest = join(root, 'supabase/functions/_shared/core');
const check = process.argv.includes('--check');
const HEADER = '// GENERATED by scripts/sync-core.mjs from js/core. Edit the original, then run `npm run sync`.\n';

const files = Object.fromEntries(
  readdirSync(src).filter((f) => f.endsWith('.js')).map((f) => [f, HEADER + readFileSync(join(src, f), 'utf8')])
);
const words = readFileSync(join(root, 'data/dictionary.txt'), 'utf8');
files['dictionary.js'] = `${HEADER}// ENABLE word list (public domain), filtered by scripts/build-dictionary.mjs.\nexport default ${JSON.stringify(words)};\n`;

let stale = [];
for (const [name, content] of Object.entries(files)) {
  const target = join(dest, name);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (current !== content) stale.push(name);
}
if (check) {
  if (stale.length) {
    console.error(`Edge Function core is stale (${stale.join(', ')}). Run: npm run sync`);
    process.exit(1);
  }
} else {
  mkdirSync(dest, { recursive: true });
  for (const name of stale) writeFileSync(join(dest, name), files[name]);
  console.log(stale.length ? `synced ${stale.join(', ')}` : 'already in sync');
}
